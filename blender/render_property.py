def create_box(name, x, y, w, l, h, material, rotation=0):
    """Create a box at (x, y) with dimensions w x l x h feet."""
    bpy.ops.mesh.primitive_cube_add(size=1, location=(x, y, h / 2))
    obj = bpy.context.active_object
    obj.name = name
    obj.scale = (w, l, h)
    obj.rotation_euler.z = rotation
    obj.data.materials.append(material)
    return obj


def create_roof(name, x, y, w, l, h_base, h_peak, material, rotation=0):
    """Create a gable roof at (x, y)."""
    mesh = bpy.data.meshes.new(name + "_roof")
    obj = bpy.data.objects.new(name + "_Roof", mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()
    hw, hl = w / 2, l / 2
    v0 = bm.verts.new((-hw, -hl, h_base))
    v1 = bm.verts.new((hw, -hl, h_base))
    v2 = bm.verts.new((hw, hl, h_base))
    v3 = bm.verts.new((-hw, hl, h_base))
    v4 = bm.verts.new((0, -hl, h_base + h_peak))
    v5 = bm.verts.new((0, hl, h_base + h_peak))

    bm.faces.new([v0, v1, v4])
    bm.faces.new([v2, v3, v5])
    bm.faces.new([v0, v4, v5, v3])
    bm.faces.new([v1, v2, v5, v4])

    bm.to_mesh(mesh)
    bm.free()
    obj.location = (x, y, 0)
    obj.rotation_euler.z = rotation
    obj.data.materials.append(material)
    return obj


def create_polygon(name, coords_ft, height, material, z_base=0):
    """Create extruded polygon from list of (x,y) coordinates."""
    mesh = bpy.data.meshes.new(name)
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.collection.objects.link(obj)

    bm = bmesh.new()
    # Bottom face
    bottom_verts = [bm.verts.new((x, y, z_base)) for x, y in coords_ft]
    bottom_face = bm.faces.new(bottom_verts)

    if height > 0.2:
        # Top face
        top_verts = [bm.verts.new((x, y, z_base + height)) for x, y in coords_ft]
        top_face = bm.faces.new(top_verts)
        # Side faces
        n = len(coords_ft)
        for i in range(n):
            j = (i + 1) % n
            bm.faces.new([bottom_verts[i], bottom_verts[j],
                         top_verts[j], top_verts[i]])

    bm.to_mesh(mesh)
    bm.free()
    obj.data.materials.append(material)
    return obj


def create_oval(name, cx, cy, rx, ry, height, material, segments=24, z_base=0):
    """Create an oval/ellipse extruded mesh."""
    coords = []
    for i in range(segments):
        angle = 2 * math.pi * i / segments
        x = cx + rx * math.cos(angle)
        y = cy + ry * math.sin(angle)
        coords.append((x, y))
    return create_polygon(name, coords, height, material, z_base)


