# Reference point — use SW-most corner as origin
# SW = min lon (most west) + min lat (most south)
ref_idx = min(range(len(boundary_coords)),
              key=lambda i: boundary_coords[i][0] + boundary_coords[i][1])
REF_LON, REF_LAT = boundary_coords[ref_idx]

DEG_TO_FT_LON = math.cos(math.radians(REF_LAT)) * 111_320 * 3.28084
DEG_TO_FT_LAT = 111_320 * 3.28084


def gps_to_ft(lon, lat):
    """Convert GPS (lon, lat) to local feet with reference point as (0, 0)."""
    return ((lon - REF_LON) * DEG_TO_FT_LON,
            (lat - REF_LAT) * DEG_TO_FT_LAT)


# Convert parcel boundary to feet
