structure_centers = []  # for tree collision avoidance

for s in structures_db:
    name = s['name'].replace(' ', '_').replace('#', '').replace('(', '').replace(')', '')
    stype = s.get('structure_type', 'other')
    height = float(s.get('height_ft') or 0)
    roof_type = s.get('roof_type')
    material = get_material(s)

    # Skip utility structures that are underground
    if s.get('material') == 'underground' and height == 0:
        continue

    # Get footprint from DB geometry
    geom = s.get('footprint_geom')
    if not geom:
        print(f"  SKIP {s['name']} — no footprint_geom")
        continue

    # Parse GeoJSON polygon coordinates
    ring = geom['coordinates'][0]
    if ring[-1] == ring[0]:
        ring = ring[:-1]
    coords_ft = [gps_to_ft(c[0], c[1]) for c in ring]

    # Compute centroid for this structure
    scx = sum(c[0] for c in coords_ft) / len(coords_ft)
    scy = sum(c[1] for c in coords_ft) / len(coords_ft)
    structure_centers.append((scx, scy))

    print(f"  {s['name']}: {len(coords_ft)} verts, height={height}, "
          f"center=({scx:.0f},{scy:.0f})")

    # Special handling for pool
    if 'pool' in s['name'].lower() or 'swim' in s['name'].lower():
        # Pool rim (concrete deck)
        create_polygon_mesh(name + "_Rim", coords_ft, 1.0,
                          MATERIALS['concrete'], z_base=0.02)
        # Pool water (inset, flush on top)
        margin = 2  # ft inset
        pool_cx = sum(c[0] for c in coords_ft) / len(coords_ft)
        pool_cy = sum(c[1] for c in coords_ft) / len(coords_ft)
        inset = []
        for c in coords_ft:
            dx = c[0] - pool_cx
            dy = c[1] - pool_cy
            dist = math.sqrt(dx**2 + dy**2)
            if dist > 0:
                scale = (dist - margin) / dist
                inset.append((pool_cx + dx * scale, pool_cy + dy * scale))
            else:
                inset.append(c)
        create_polygon_mesh(name + "_Water", inset, 0.2,
                          MATERIALS['pool_water'], z_base=1.1)
        continue

    # Special handling for driveway/gravel
    if 'driveway' in s['name'].lower() or 'gravel' in s['name'].lower():
        create_polygon_mesh(name, coords_ft, 0.15, MATERIALS['gravel'], z_base=0.02)
        continue

    # Special handling for deck (low height)
    if stype == 'deck':
        create_polygon_mesh(name, coords_ft, max(height, 1.5),
                          MATERIALS['wood_deck'], z_base=0.05)
        continue

    # Regular structure — extrude footprint to height
    if height < 1:
        height = 8  # default height if not specified

    create_polygon_mesh(name, coords_ft, height, material)

    # Add roof if applicable
    if roof_type and roof_type not in ('none', 'flat'):
        peak = 4 if height < 12 else 6
        create_roof_from_footprint(name, coords_ft, height, peak,
                                  MATERIALS['roof'])

