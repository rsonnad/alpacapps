# 8.  SETBACK LINES — from parcel edges
# ---------------------------------------------------------------------------
setback_distances = {
    'S': (0, 1, 20),   # SW→SE edge, 20 ft setback (road)
    'E': (1, 2, 10),   # SE→NE edge, 10 ft
    'N_east': (2, 3, 10),   # NE→N-mid, 10 ft
    'N_west': (3, 4, 10),   # N-mid→NW, 10 ft
    'W_upper': (4, 5, 10),   # NW→W-mid, 10 ft
    'W_lower': (5, 0, 10),   # W-mid→SW, 10 ft
}

for label, (i_start, i_end, dist) in setback_distances.items():
    p_start = parcel_ft[i_start]
    p_end = parcel_ft[i_end]

    # Compute inward normal
    dx = p_end[0] - p_start[0]
    dy = p_end[1] - p_start[1]
    length = math.sqrt(dx**2 + dy**2)
    if length < 0.01:
        continue
    nx, ny = -dy / length, dx / length
    # Ensure normal points inward (toward centroid)
    mid_x = (p_start[0] + p_end[0]) / 2
    mid_y = (p_start[1] + p_end[1]) / 2
    if nx * (cx - mid_x) + ny * (cy - mid_y) < 0:
        nx, ny = -nx, -ny

    p1 = (p_start[0] + nx * dist, p_start[1] + ny * dist, 0.05)
    p2 = (p_end[0] + nx * dist, p_end[1] + ny * dist, 0.05)

    strip_w = 0.5
    perp_x = -dy / length * strip_w
    perp_y = dx / length * strip_w

    mesh_sb = bpy.data.meshes.new(f"Setback_{label}")
    obj_sb = bpy.data.objects.new(f"Setback_{label}", mesh_sb)
    bpy.context.collection.objects.link(obj_sb)
    bm = bmesh.new()
    sv = [
        bm.verts.new((p1[0] - perp_x, p1[1] - perp_y, 0.05)),
        bm.verts.new((p2[0] - perp_x, p2[1] - perp_y, 0.05)),
        bm.verts.new((p2[0] + perp_x, p2[1] + perp_y, 0.05)),
        bm.verts.new((p1[0] + perp_x, p1[1] + perp_y, 0.05)),
    ]
    bm.faces.new(sv)
    bm.to_mesh(mesh_sb)
    bm.free()
    obj_sb.data.materials.append(mat_setback)

