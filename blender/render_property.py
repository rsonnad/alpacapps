# 8.  SETBACK LINES — from DB edge geometries
# ---------------------------------------------------------------------------
for edge in edges_db:
    geom = edge.get('edge_geom')
    if not geom:
        continue

    side = edge['edge_side']
    setback_ft = float(edge.get('setback_required_ft') or 10)
    coords = geom['coordinates']
    p_start = gps_to_ft(coords[0][0], coords[0][1])
    p_end = gps_to_ft(coords[1][0], coords[1][1])

    dx = p_end[0] - p_start[0]
    dy = p_end[1] - p_start[1]
    length = math.sqrt(dx**2 + dy**2)
    if length < 0.01:
        continue

    nx, ny = -dy / length, dx / length
    mid_x = (p_start[0] + p_end[0]) / 2
    mid_y = (p_start[1] + p_end[1]) / 2
    if nx * (cx - mid_x) + ny * (cy - mid_y) < 0:
        nx, ny = -nx, -ny

    s1 = (p_start[0] + nx * setback_ft, p_start[1] + ny * setback_ft, 0.05)
    s2 = (p_end[0] + nx * setback_ft, p_end[1] + ny * setback_ft, 0.05)

    strip_w = 0.5
    perp_x = -dy / length * strip_w
    perp_y = dx / length * strip_w

    mesh_sb = bpy.data.meshes.new(f"Setback_{side}")
    obj_sb = bpy.data.objects.new(f"Setback_{side}", mesh_sb)
    bpy.context.collection.objects.link(obj_sb)
    bm = bmesh.new()
    sv = [
        bm.verts.new((s1[0] - perp_x, s1[1] - perp_y, 0.05)),
        bm.verts.new((s2[0] - perp_x, s2[1] - perp_y, 0.05)),
        bm.verts.new((s2[0] + perp_x, s2[1] + perp_y, 0.05)),
        bm.verts.new((s1[0] + perp_x, s1[1] + perp_y, 0.05)),
    ]
    bm.faces.new(sv)
    bm.to_mesh(mesh_sb)
    bm.free()
    obj_sb.data.materials.append(MATERIALS['setback'])

