def get_material(structure):
    """Pick material based on structure's material, color, and type fields."""
    mat_name = (structure.get('material') or '').lower()
    color = (structure.get('color') or '').lower()
    stype = structure.get('structure_type', '')

    # Color-specific containers
    if stype == 'container':
        if 'red' in color or 'red' in structure.get('name', '').lower():
            return MATERIALS['steel_red']
        if 'beige' in color or 'beige' in structure.get('name', '').lower():
            return MATERIALS['steel_beige']
        if 'blue' in color or '#3' in structure.get('name', ''):
            return MATERIALS['steel_blue']
        return MATERIALS['steel']

    # Material mapping
    mat_map = {
        'stone_frame': 'stone_frame',
        'stone': 'stone_frame',
        'wood': 'wood',
        'rv': 'rv',
        'steel_container': 'steel',
        'steel': 'steel',
        'gravel': 'gravel',
        'concrete': 'concrete',
        'underground': 'underground',
    }

    if mat_name in mat_map:
        return MATERIALS[mat_map[mat_name]]

    # Type-based fallback
    type_map = {
        'house': 'stone_frame',
        'outbuilding': 'wood',
        'deck': 'wood_deck',
        'sauna': 'wood',
        'trailer_rv': 'rv',
        'container': 'steel',
        'utility': 'underground',
    }
    return MATERIALS.get(type_map.get(stype, 'wood'), MATERIALS['wood'])


